SELECT D1.IME || ' ' || D1.PREZIME, D2.IME || ' ' || D2.PREZIME
FROM DA.DOSIJE AS D1 JOIN DA.DOSIJE AS D2
ON D1.INDEKS < D2.INDEKS AND YEAR(DATE(D1.DATUPISA)) = YEAR(DATE(D2.DATUPISA))
AND D1.IDPROGRAMA = D2.IDPROGRAMA
WHERE EXISTS(SELECT*
             FROM DA.ISPIT AS I1 JOIN DA.PREDMET AS P ON P.ID = I1.IDPREDMETA
             WHERE I1.INDEKS = D1.INDEKS
             AND I1.STATUS = 'o' AND I1.OCENA > 5
             AND P.ESPB >= 8) AND EXISTS(SELECT*
             FROM DA.ISPIT AS I1 JOIN DA.PREDMET AS P ON P.ID = I1.IDPREDMETA
             WHERE I1.INDEKS = D2.INDEKS
             AND I1.STATUS = 'o' AND I1.OCENA > 5
             AND P.ESPB >= 8);

SELECT D.INDEKS, D.IME || ' '||D.PREZIME ||' je pao ' || COUNT(*) || ' ispita' AS KOMENTAR
FROM DA.DOSIJE AS D JOIN DA.ISPIT AS I ON I.INDEKS = D.INDEKS
AND I.OCENA = 5 AND I.STATUS = 'o' JOIN DA.STUDENTSKISTATUS AS SS
ON SS.ID = D.IDSTATUSA AND POSITION('budzet', lower(ss.NAZIV)) > 0
GROUP BY D.INDEKS, D.IME, D.PREZIME
HAVING COUNT(*) > 5
UNION
SELECT D1.INDEKS, D1.IME || ' ' || D1.PREZIME || ' nije pao ni jedan ispit'
FROM DA.DOSIJE AS D1 JOIN DA.STUDENTSKISTATUS AS SS1 ON SS1.ID = D1.IDSTATUSA
AND POSITION('samofinansiranje', LOWER(ss1.NAZIV)) > 0
WHERE NOT EXISTS(SELECT*
                 FROM DA.ISPIT AS I1
                 WHERE I1.INDEKS = D1.INDEKS AND I1.STATUS = 'o' AND I1.OCENA = 5);


CREATE TABLE STATS(
    INDEKS INTEGER NOT NULL PRIMARY KEY,
    BROJ_POLOZENIH INTEGER,
    BROJ_PALIH INTEGER,
    UDEO_POLOZENIH DOUBLE,
    DATUM_UNOSA DATE
);

CREATE FUNCTION IZRACUNAJ_UDEO(A INTEGER, B INTEGER)
RETURNS DOUBLE
RETURN VALUES(CASE WHEN A = 0 AND B = 0 THEN 0.0
             ELSE (A*1.0)/(A*1.0+B*1.0) END);

INSERT INTO STATS(INDEKS, BROJ_POLOZENIH, BROJ_PALIH, DATUM_UNOSA)
SELECT D.INDEKS, SUM(CASE WHEN I.OCENA > 5 AND I.STATUS = 'o' THEN 1 ELSE 0 END),
       SUM(CASE WHEN I.OCENA = 5 AND I.STATUS = 'o' THEN 1 ELSE 0 END), CURRENT_DATE
FROM DA.DOSIJE AS D LEFT JOIN DA.ISPIT AS I ON I.INDEKS = D.INDEKS
GROUP BY D.INDEKS;

UPDATE STATS
SET UDEO_POLOZENIH = IZRACUNAJ_UDEO(BROJ_POLOZENIH, BROJ_PALIH)
WHERE BROJ_POLOZENIH > BROJ_PALIH;

SELECT INDEKS, BROJ_POLOZENIH, BROJ_PALIH, UDEO_POLOZENIH, DATUM_UNOSA
FROM STATS;

DELETE FROM STATS
WHERE UDEO_POLOZENIH IS NULL OR BROJ_PALIH=BROJ_POLOZENIH;

DROP TABLE STATS;
DROP FUNCTION IZRACUNAJ_UDEO;