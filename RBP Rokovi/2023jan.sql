SELECT DISTINCT CASE WHEN POL = 'z' THEN 'STUDENTKINJA'
        ELSE 'STUDENT' END || ' ' || IME || ' ' || PREZIME AS IME,
    D.INDEKS, D.DATUPISA, SP.NAZIV, COALESCE(P.NAZIV, 'Nema polozenih predmeta')
FROM DA.DOSIJE AS D JOIN DA.STUDIJSKIPROGRAM AS SP
    ON SP.ID = D.IDPROGRAMA LEFT JOIN DA.ISPIT AS I
    ON I.INDEKS = D.INDEKS AND I.STATUS = 'o' AND I.OCENA >5
    LEFT JOIN DA.PREDMET AS P ON P.ID = I.IDPREDMETA
WHERE NOT EXISTS(SELECT *
                 FROM DA.DOSIJE AS D1
                 WHERE D1.IDPROGRAMA = D.IDPROGRAMA
                 AND D.DATUPISA > D1.DATUPISA AND D1.MESTORODJENJA LIKE '%Beograd%')
    AND D.MESTORODJENJA LIKE '%Beograd%';

WITH PROSEK_MESTA AS(
    SELECT D.MESTORODJENJA, AVG(I.OCENA*1.0) AS PROSEK
    FROM DA.DOSIJE AS D JOIN DA.ISPIT AS I
    ON I.INDEKS = D.INDEKS AND I.OCENA > 5 AND I.STATUS = 'o'
    GROUP BY D.MESTORODJENJA
), PROSEK_STUDENTA AS(
    SELECT INDEKS, AVG(OCENA*1.0) AS PROSEK
    FROM DA.ISPIT
    WHERE STATUS = 'o' AND OCENA > 5
    GROUP BY INDEKS
)
SELECT IME || ' ' || PREZIME || ' ima bolji prosek od ' || D.MESTORODJENJA AS KOMENTAR,
       PS.PROSEK - PM.PROSEK AS "Razlika proseka studenta i proseka mesta"
FROM DA.DOSIJE AS D JOIN PROSEK_MESTA AS PM ON PM.MESTORODJENJA = D.MESTORODJENJA
    JOIN PROSEK_STUDENTA AS PS ON PS.INDEKS = D.INDEKS
WHERE PS.PROSEK > PM.PROSEK AND CURRENT_DATE - 4 YEARS > DATE(D.DATUPISA)
AND D.DATDIPLOMIRANJA IS NULL;

CREATE TABLE STUDENT_INFO(
    INDEKS INTEGER  NOT NULL PRIMARY KEY,
    MEJL VARCHAR(50),
    MAX_OCENA SMALLINT,
    MIN_OCENA SMALLINT,
    ARITMETICKA_SREDINA DOUBLE DEFAULT 5.0
);

CREATE FUNCTION MEJL_ADRESA(I INT)
RETURNS VARCHAR(50)
RETURN SELECT LOWER( IME||'.'||PREZIME || '.' || SUBSTR(SP.NAZIV, 1,1)
       || SP.ID / 100 || '@student.matf')
        FROM DA.DOSIJE AS D JOIN DA.STUDIJSKIPROGRAM AS SP
        ON D.IDPROGRAMA = SP.ID
        WHERE D.INDEKS = I;

--#SET TERMINATOR @
CREATE TRIGGER UNOS
    BEFORE INSERT ON STUDENT_INFO
    REFERENCING NEW AS N
    FOR EACH ROW
    WHEN (N.MIN_OCENA IS NULL AND N.MAX_OCENA IS NULL)
         BEGIN ATOMIC
             SET N.MIN_OCENA = (SELECT MIN(OCENA)
                                FROM DA.ISPIT
                                WHERE STATUS = 'o' AND OCENA > 5 AND INDEKS = N.INDEKS);
             SET N.MAX_OCENA = (SELECT MAX(OCENA)
                                FROM DA.ISPIT WHERE STATUS = 'o' AND OCENA >5
                                AND INDEKS = N.INDEKS);
             SET N.ARITMETICKA_SREDINA = (N.MIN_OCENA+N.MAX_OCENA)/2.0;
         END;

INSERT INTO STUDENT_INFO(INDEKS, MEJL)
    SELECT INDEKS, MEJL_ADRESA(INDEKS)
    FROM DA.DOSIJE AS D JOIN DA.STUDENTSKISTATUS AS SS ON SS.ID = D.IDSTATUSA
    WHERE LOWER(SS.NAZIV) LIKE 'samofinansiranje';

DELETE FROM STUDENT_INFO
WHERE MIN_OCENA = MAX_OCENA OR ARITMETICKA_SREDINA IS NULL;

