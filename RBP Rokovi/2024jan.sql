SELECT IME || ' ' || PREZIME || ' (' || CASE WHEN MESTORODJENJA LIKE '%Beograd%' THEN 'BG' ELSE MESTORODJENJA END|| ')' AS KOD, AVG(OCENA*1.0)
FROM DA.DOSIJE AS D JOIN DA.STUDIJSKIPROGRAM AS SP ON SP.ID = D.IDPROGRAMA
    LEFT JOIN DA.ISPIT AS I ON I.INDEKS = D.INDEKS
    AND I.OCENA > 5 AND I.STATUS = 'o'
WHERE SP.NAZIV LIKE '%Informatika%' AND EXISTS(SELECT*
FROM DA.ISPIT AS I1 WHERE I1.STATUS = 'x' AND I1.INDEKS = D.INDEKS)
GROUP BY D.INDEKS, D.IME, D.PREZIME, D.MESTORODJENJA;

WITH JEDINI AS(
    SELECT D.INDEKS, SKGODINA
    FROM DA.UPISGODINE AS UG JOIN DA.DOSIJE AS D ON D.INDEKS = UG.INDEKS
    WHERE NOT EXISTS(SELECT*
                     FROM DA.UPISGODINE AS UG1 JOIN DA.DOSIJE AS D1
                     ON D1.INDEKS = UG1.INDEKS
                     WHERE D1.MESTORODJENJA = D.MESTORODJENJA
                     AND UG1.SKGODINA = UG.SKGODINA AND D1.INDEKS <> D.INDEKS)
), MANJNEODPET AS(
    SELECT D.INDEKS, SUM(CASE WHEN PP.VRSTA = 'obavezan' THEN 1 ELSE 0 END) AS BROJ
    FROM DA.DOSIJE AS D LEFT JOIN DA.ISPIT AS I ON I.INDEKS = D.INDEKS
    AND I.OCENA > 5 AND I.STATUS = 'o' LEFT JOIN DA.PREDMETPROGRAMA AS PP ON PP.IDPREDMETA = I.IDPREDMETA
    GROUP BY D.INDEKS
    HAVING SUM(CASE WHEN PP.VRSTA = 'obavezan' THEN 1 ELSE 0 END) < 5
)
SELECT IME || ' ' || PREZIME AS "Ime i prezime", 'Student je jedini iz mesta ' || MESTORODJENJA || ' koji je upisao ' || J.SKGODINA|| ' skgodinu',
       CURRENT_DATE - DATUPISA AS "Proteklo dana"
FROM DA.DOSIJE AS D JOIN JEDINI AS J ON J.INDEKS = D.INDEKS JOIN MANJNEODPET AS M ON M.INDEKS = D.INDEKS
ORDER BY "Proteklo dana" DESC;

CREATE TABLE STATS(
    MESTO VARCHAR(30) NOT NULL PRIMARY KEY,
    BROJ_STUDENATA INTEGER,
    BROJ_DIPLOMIRANIH INTEGER,
    UDEO_STUDENATA DECIMAL(5) DEFAULT 0.0
);

CREATE FUNCTION IZRACUNAJ_UDEO(MESTO VARCHAR(30))
RETURNS DECIMAL
RETURN (SELECT DECIMAL(SUM(CASE WHEN POSITION(MESTO,D.MESTORODJENJA) > 0 THEN 1.0 ELSE 0.0
    END)*100.0/COUNT(DISTINCT INDEKS)*1.0, 5,2)
        FROM DA.DOSIJE AS D
        );

DROP FUNCTION IZRACUNAJ_UDEO;

VALUES IZRACUNAJ_UDEO('Podgorica');

CREATE TRIGGER NEKITRIGGER
    BEFORE INSERT ON STATS
    REFERENCING NEW AS N
    FOR EACH ROW
         BEGIN ATOMIC
             SET N.UDEO_STUDENATA = IZRACUNAJ_UDEO(N.MESTO);
         end;

INSERT INTO STATS(MESTO, BROJ_STUDENATA, BROJ_DIPLOMIRANIH)
SELECT DISTINCT MESTORODJENJA, COUNT(DISTINCT INDEKS), SUM(CASE WHEN DATDIPLOMIRANJA IS NOT NULL THEN 1 ELSE 0 END)
FROM DA.DOSIJE
WHERE SUBSTR(MESTORODJENJA,1,1) = 'B'
GROUP BY MESTORODJENJA;

DROP FUNCTION IZRACUNAJ_UDEO;
DROP TABLE STATS;
DROP TRIGGER NEKITRIGGER;
