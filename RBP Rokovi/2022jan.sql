CREATE TABLE DIPLOMIRANI(
    INDEKS INTEGER NOT NULL PRIMARY KEY,
    POLOZENO_ESPB INTEGER DEFAULT 0,
    PROSEK DOUBLE DEFAULT 0.0,
    DATUM_PRVOG_POLOZENOG DATE
);

CREATE TABLE DOSIJE1 AS(
    SELECT D.*
    FROM DA.DOSIJE AS D
) WITH DATA;

CREATE TRIGGER UNOS
    BEFORE UPDATE OF DATDIPLOMIRANJA ON DOSIJE1
    REFERENCING OLD AS O
                NEW AS N
    FOR EACH ROW
    WHEN(O.DATDIPLOMIRANJA IS NULL AND N.DATDIPLOMIRANJA IS NOT NULL)
    BEGIN
        INSERT INTO DIPLOMIRANI
            SELECT I.INDEKS, COUNT(ESPB), COUNT(OCENA*1.0), MIN(DATPOLAGANJA)
            FROM DA.ISPIT AS I JOIN DA.PREDMET AS P ON P.ID = I.IDPREDMETA
            WHERE O.INDEKS = I.INDEKS
            GROUP BY I.INDEKS;
    end;

UPDATE DOSIJE1
SET DATDIPLOMIRANJA = CURRENT DATE
WHERE INDEKS IN (SELECT INDEKS
                 FROM DA.ISPIT AS I
                 WHERE I.STATUS = 'o' AND I.OCENA > 5 AND I.INDEKS / 10000 = 2015);

DELETE FROM DIPLOMIRANI AS DIP
WHERE DIP.INDEKS IN (SELECT UG.INDEKS
                     FROM DA.UPISGODINE AS UG JOIN DA.STUDENTSKISTATUS AS SS
                     ON UG.IDSTATUSA = SS.ID
                     WHERE LOWER(SS.NAZIV) LIKE 'mirovanje%');

DROP TABLE DIPLOMIRANI;

CREATE TABLE PREDMET_STAT(
    IDPREDMETA INTEGER NOT NULL PRIMARY KEY,
    PRIJAVILO INTEGER,
    POLOZILO INTEGER
);

INSERT INTO PREDMET_STAT(IDPREDMETA, PRIJAVILO, POLOZILO)
SELECT IDPREDMETA, COUNT(*), SUM(CASE WHEN OCENA > 5 AND STATUS = 'o' THEN 1 ELSE 0 END)
       FROM DA.ISPIT
       GROUP BY IDPREDMETA;

CREATE TRIGGER PROMENA
    AFTER UPDATE OF STATUS ON DA.ISPIT
    REFERENCING OLD AS O
                NEW AS N
    FOR EACH ROW
    WHEN(O.STATUS = 'p' AND N.STATUS = 'o' AND N.OCENA > 5)
    BEGIN
        UPDATE PREDMET_STAT AS PS
        SET (POLOZILO, PRIJAVILO) = (POLOZILO+1, PRIJAVILO-1)
        WHERE PS.IDPREDMETA = O.IDPREDMETA;
    end;

UPDATE DA.ISPIT
SET (STATUS, OCENA) = ('o', 10)
WHERE STATUS = 'p' AND IDPREDMETA IN (SELECT A.IDPREDMETA
                                      FROM DA.PREDMETPROGRAMA AS  A
                                      JOIN DA.STUDIJSKIPROGRAM AS B
                                      ON B.ID = A.IDPROGRAMA
                                      JOIN DA.NIVOKVALIFIKACIJE AS C ON C.ID = B.IDNIVOA
                                      WHERE C.ID = 3);

DROP TABLE PREDMET_STAT;
