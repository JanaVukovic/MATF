SELECT D.INDEKS, D.IME, D.PREZIME, COALESCE(P.NAZIV, 'Nema ponisteni predmet'),
       CURRENT_DATE - DATE(I.DATPOLAGANJA), I.OCENA
FROM DA.DOSIJE AS D LEFT JOIN DA.ISPIT AS I ON I.INDEKS = D.INDEKS
AND I.STATUS = 'x' AND I.OCENA > 5 LEFT JOIN DA.PREDMET AS P ON P.ID = I.IDPREDMETA
WHERE EXISTS(SELECT*
             FROM DA.DOSIJE AS D2
             WHERE D2.INDEKS <> D.INDEKS AND D2.MESTORODJENJA = D.MESTORODJENJA
             AND YEAR(DATE(D2.DATUPISA)) = YEAR(DATE(D.DATUPISA)));

WITH NAJ AS(
    SELECT PP.IDPROGRAMA, UK.IDPREDMETA, COUNT(DISTINCT UK.INDEKS) AS BROJ
    FROM DA.PREDMETPROGRAMA AS PP JOIN DA.UPISANKURS AS UK
    ON UK.IDPREDMETA = PP.IDPREDMETA
    WHERE PP.VRSTA LIKE 'izborni'
    GROUP BY PP.IDPROGRAMA, UK.IDPREDMETA
    HAVING COUNT(DISTINCT UK.INDEKS) >= 10
)
SELECT SP.ID, SP.NAZIV, P.NAZIV, COUNT(*), COUNT(CASE WHEN I.OCENA > 5 AND I.STATUS = 'o' THEN 1 ELSE NULL END),
       AVG(CASE WHEN I.OCENA > 5 AND I.STATUS = 'o' THEN I.OCENA*1.0 ELSE NULL END)
FROM NAJ AS N JOIN DA.STUDIJSKIPROGRAM AS SP ON SP.ID = N.IDPROGRAMA
JOIN DA.PREDMET AS P ON P.ID = N.IDPREDMETA LEFT JOIN DA.ISPIT AS I
ON I.IDPREDMETA = P.ID
WHERE N.BROJ = (SELECT MAX(A.BROJ)
                FROM NAJ AS A
                WHERE A.IDPROGRAMA = N.IDPROGRAMA)
GROUP BY SP.ID, SP.NAZIV, P.NAZIV
ORDER BY SP.ID;

CREATE TABLE EKSKURZIJA(
    INDEKS INTEGER NOT NULL PRIMARY KEY,
    CENA INTEGER NOT NULL DEFAULT 50000,
    STATUS_PLACANJA VARCHAR(30),
    FOREIGN KEY fk_indeks (INDEKS) REFERENCES DA.DOSIJE
);

ALTER TABLE EKSKURZIJA ADD CONSTRAINT const_status_placanja check (STATUS_PLACANJA IN ('placeno', 'oslobodjen','neplaceno'));
ALTER TABLE EKSKURZIJA ALTER COLUMN STATUS_PLACANJA SET DEFAULT 'neplaceno';

INSERT INTO EKSKURZIJA(INDEKS)
SELECT D.INDEKS
FROM DA.DOSIJE AS D
WHERE SUBSTR(D.PREZIME, 2,1) = 'a' AND YEAR(DATE(D.DATUPISA)) BETWEEN 2017 AND 2021
AND 3 <= (SELECT COUNT(*)
          FROM DA.UPISGODINE AS UG
          WHERE UG.INDEKS = D.INDEKS);

MERGE INTO EKSKURZIJA AS E
    USING (SELECT D.INDEKS, COUNT(CASE WHEN I.OCENA = 10 THEN 1 ELSE NULL END) AS DESET,
                  COUNT(*) AS SVE
           FROM DA.DOSIJE AS D LEFT JOIN DA.ISPIT AS I ON I.INDEKS = D.INDEKS
           AND I.OCENA > 5 AND I.STATUS = 'o'
           WHERE D.DATDIPLOMIRANJA IS NULL
           GROUP BY D.INDEKS) AS TMP
    ON TMP.INDEKS = E.INDEKS
WHEN MATCHED THEN
    UPDATE SET E.CENA = E.CENA - E.CENA*(TMP.DESET*1.0/TMP.SVE*1.0)
WHEN MATCHED AND TMP.SVE = TMP.DESET THEN
    UPDATE SET E.STATUS_PLACANJA = 'oslobodjen',
               E.CENA = 0
WHEN NOT MATCHED THEN
    INSERT(INDEKS, CENA) VALUES(TMP.INDEKS, 50000);

DROP TABLE EKSKURZIJA;