SELECT D.INDEKS, D.IME, D.PREZIME, SUBSTR(D.MESTORODJENJA, 1,2),
       YEAR(DATE(D.DATUPISA)), MONTHNAME(DATE(D.DATUPISA)), PI.NAZIVPREDMETA
FROM DA.DOSIJE AS D JOIN DA.PRIZNATISPIT AS PI
ON PI.INDEKS = D.INDEKS
WHERE EXISTS(SELECT*
             FROM DA.PRIZNATISPIT AS PI1
             WHERE PI1.INDEKS = D.INDEKS AND PI1.ESPB = 6);

WITH PROSEK AS(
    SELECT INDEKS, AVG(OCENA*1.0) AS PROSEK
    FROM DA.ISPIT
    WHERE OCENA > 5 AND STATUS = 'o'
    GROUP BY INDEKS
),PRIJAVA AS(
    SELECT INDEKS, COUNT(*) AS PRIJAVE
    FROM DA.ISPIT
    WHERE STATUS = 'p'
    GROUP BY INDEKS
),POLOZENO AS(
    SELECT D.INDEKS, COUNT(*) AS POLOZENO
    FROM DA.DOSIJE AS D LEFT JOIN DA.PRIZNATISPIT AS PI ON PI.INDEKS = D.INDEKS
    GROUP BY D.INDEKS
)
SELECT D.INDEKS, D.IME, D.PREZIME
FROM DA.DOSIJE AS D JOIN PROSEK AS P ON P.INDEKS = D.INDEKS
JOIN POLOZENO AS PO ON PO.INDEKS = D.INDEKS JOIN PRIJAVA AS PR
ON PR.INDEKS = D.INDEKS
WHERE PR.PRIJAVE >= 3 AND EXISTS(SELECT*
                                 FROM DA.ISPIT AS I
                                 WHERE I.INDEKS = D.INDEKS
                                 AND I.POENI = (SELECT MAX(POENI)
                                                FROM DA.ISPIT AS I1
                                                JOIN DA.DOSIJE AS D2
                                                ON I1.INDEKS = D2.INDEKS
                                                WHERE D2.IDPROGRAMA = D.IDPROGRAMA
                                                ));

CREATE TABLE ISPITNI_ROK_STAT(
    OZNAKAROKA VARCHAR(20) NOT NULL,
    SKGODINA INTEGER NOT NULL,
    BRPREDMETA INTEGER DEFAULT 0,
    PROSEK DOUBLE DEFAULT 0.0,
    primary key (skgodina, OZNAKAROKA),
    CONSTRAINT za_prosek check(PROSEK BETWEEN 0.0 AND 10.0)
);

DROP TABLE ISPITNI_ROK_STAT;

insert into ISPITNI_ROK_STAT(OZNAKAROKA, SKGODINA, BRPREDMETA)
SELECT IR.OZNAKAROKA, IR.SKGODINA, COUNT(DISTINCT I.IDPREDMETA)
FROM DA.ISPITNIROK AS IR JOIN DA.ISPIT AS I ON I.OZNAKAROKA = IR.OZNAKAROKA
AND I.SKGODINA = IR.SKGODINA
GROUP BY IR.OZNAKAROKA, IR.SKGODINA;

MERGE INTO ISPITNI_ROK_STAT AS IRS
USING(SELECT IR.OZNAKAROKA, IR.SKGODINA, COALESCE(COUNT(DISTINCT I.IDPREDMETA), 0) AS BROJ,
      COALESCE(AVG(CASE WHEN I.OCENA > 5 AND I.STATUS = 'o' THEN I.OCENA*1.0
      ELSE NULL END), 0.0) AS PROSEK
      FROM DA.ISPITNIROK AS IR LEFT JOIN DA.ISPIT AS I ON I.SKGODINA = IR.SKGODINA AND I.OZNAKAROKA = IR.OZNAKAROKA
      GROUP BY IR.OZNAKAROKA, IR.SKGODINA) AS TMP
ON IRS.SKGODINA = TMP.SKGODINA AND IRS.OZNAKAROKA = TMP.OZNAKAROKA
WHEN MATCHED AND IRS.SKGODINA > 2018 THEN
UPDATE SET IRS.PROSEK = TMP.PROSEK
WHEN MATCHED AND IRS.SKGODINA <= 2018 THEN
UPDATE SET IRS.BRPREDMETA = TMP.BROJ
WHEN NOT MATCHED THEN
INSERT(OZNAKAROKA, SKGODINA, BRPREDMETA, PROSEK) VALUES(TMP.OZNAKAROKA, TMP.SKGODINA, TMP.BROJ, TMP.PROSEK);


DROP TABLE ISPITNI_ROK_STAT;