CREATE TABLE STATISTIKA_PREDMETA(
    ID INTEGER PRIMARY KEY,
    POLOZILO INTEGER,
    PALO INTEGER,
    PONISTILO INTEGER,
    USLOVLJENO INTEGER,
    USLOVLJAVA INTEGER,
    FOREIGN KEY fk_id (ID) REFERENCES DA.PREDMET
);


CREATE FUNCTION INFORMACIJE_ISPITNI_ROK(VAR_SKGODINA INTEGER,
VAR_OZNAKAROKA VARCHAR(30), VAR_OCENA INTEGER)
RETURNS VARCHAR(100)
RETURN (SELECT CASE WHEN COUNT(*) = 0 THEN 'Ne moze' ELSE
'Polozeno ' || COUNT(*) || ' ispita sa ocenom ' || VAR_OCENA END
    FROM DA.ISPIT AS I
    WHERE I.OZNAKAROKA = VAR_OZNAKAROKA AND I.SKGODINA = VAR_SKGODINA
    AND I.STATUS = 'o' AND I.OCENA = VAR_OCENA AND I.OCENA > 5);

INSERT INTO STATISTIKA_PREDMETA(ID, POLOZILO, PALO, PONISTILO)
SELECT I.IDPREDMETA, SUM(CASE WHEN I.OCENA > 5 AND I.STATUS = 'o' THEN 1 ELSE 0 END),
       SUM(CASE WHEN I.OCENA < 6 AND I.STATUS = 'o' THEN 1 ELSE 0 END),
       SUM(CASE WHEN I.STATUS = 'x' THEN 1 ELSE 0 END)
FROM DA.ISPIT AS I RIGHT JOIN DA.UPISANKURS AS UK ON UK.IDPREDMETA = I.IDPREDMETA
GROUP BY I.IDPREDMETA
HAVING COUNT(DISTINCT I.INDEKS) >= 500;

CREATE TRIGGER UNOS_STATISTIKE
    AFTER INSERT ON STATISTIKA_PREDMETA
        REFERENCING NEW AS N
    FOR EACH ROW
        BEGIN ATOMIC
            SET N.USLOVLJENO = (SELECT COUNT(DISTINCT IDUSLOVNOGPREDMETA)
            FROM DA.USLOVNIPREDMET WHERE IDPREDMETA = N.ID),
            N.USLOVLJAVA = (SELECT COUNT(DISTINCT IDPREDMETA)
            FROM DA.USLOVNIPREDMET WHERE IDUSLOVNOGPREDMETA = N.ID);
        END;

DROP TABLE STATISTIKA_PREDMETA;
DROP FUNCTION INFORMACIJE_ISPITNI_ROK;
DROP TRIGGER UNOS_STATISTIKE;
