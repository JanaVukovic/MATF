SELECT D1.INDEKS || ', ' || D1.IME || ', ' || D1.PREZIME,
       SUBSTR(D1.MESTORODJENJA, 1, 4) || SUBSTR(D1.IME, 1, 1)
        || SUBSTR(D2.IME, 1, 1)  AS "Naziv para"
FROM DA.DOSIJE AS D1 JOIN DA.ISPIT AS I1 ON I1.INDEKS = D1.INDEKS
    AND I1.STATUS = 'o' AND I1.OCENA > 5
    JOIN DA.DOSIJE AS D2
    ON SUBSTR(D1.MESTORODJENJA, 1, 4) = SUBSTR(D2.MESTORODJENJA, 1, 4)
    AND YEAR(D1.DATUPISA) = YEAR(D2.DATUPISA) AND D1.INDEKS < D2.INDEKS
    JOIN DA.ISPIT AS I2 ON I2.INDEKS= D2.INDEKS AND I2.STATUS = 'o' AND I2.INDEKS = D2.INDEKS
    AND I1.IDPREDMETA = I2.IDPREDMETA AND I1.POENI - 5 = I2.POENI;

WITH PROSEK_STUDENTA AS(
    SELECT INDEKS, AVG(OCENA) PROSEK
    FROM DA.ISPIT
    WHERE OCENA > 5 AND STATUS = 'o'
    GROUP BY INDEKS
), PROSEK_SMERA AS(
    SELECT SP.ID, AVG(OCENA) PROSEK
    FROM DA.STUDIJSKIPROGRAM AS SP JOIN DA.DOSIJE AS D ON D.IDPROGRAMA = SP.ID
    JOIN DA.ISPIT AS I ON I.INDEKS = D.INDEKS AND I.STATUS = 'o' AND I.OCENA > 5
    GROUP BY SP.ID
)
SELECT D.INDEKS, D.IME, D.PREZIME, PS.PROSEK
FROM DA.DOSIJE AS D JOIN PROSEK_STUDENTA AS PS ON PS.INDEKS = D.INDEKS
    JOIN PROSEK_SMERA AS SM ON SM.ID = D.IDPROGRAMA;

CREATE TABLE STUDENT_MENTOR(
    STUDENT INTEGER NOT NULL PRIMARY KEY,
    MENTOR INTEGER,
    DATPOCETKA DATE,
    KOMENTAR VARCHAR(200),
    CONSTRAINT FK_MENTOR FOREIGN KEY (MENTOR) REFERENCES DA.DOSIJE
);

INSERT INTO STUDENT_MENTOR (STUDENT, MENTOR, DATPOCETKA)
SELECT D1.INDEKS, MIN(D2.INDEKS), CURRENT_DATE - 1 DAYS
FROM DA.DOSIJE AS D1 JOIN DA.STUDIJSKIPROGRAM AS SP1
    ON SP1.ID = D1.IDPROGRAMA AND MOD(SP1.ID, 100) = 1
    JOIN DA.DOSIJE AS D2 JOIN DA.STUDIJSKIPROGRAM AS SP2 ON SP2.ID = D2.IDPROGRAMA
    AND SP1.NAZIV = SP2.NAZIV AND 2 = SP2.ID/100
GROUP BY D1.INDEKS;

DELETE FROM STUDENT_MENTOR
WHERE DATPOCETKA IS NULL
