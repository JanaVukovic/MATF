--1. zadatak

SELECT DISTINCT D.INDEKS, D.IME, D.PREZIME, P.NAZIV, I.OZNAKAROKA, COALESCE(I.OCENA, 'Nije polagao/la nijedan ispit petkom') as "Ocena/Poruka"
FROM DA.DOSIJE AS D JOIN DA.STUDIJSKIPROGRAM AS SP
    ON SP.ID = D.IDPROGRAMA JOIN DA.STUDENTSKISTATUS AS SS
    ON SS.ID = D.IDSTATUSA LEFT JOIN DA.ISPIT AS I ON I.INDEKS = D.INDEKS
    AND DAYOFWEEK(DATE(I.DATPOLAGANJA)) = 6 LEFT JOIN DA.PREDMET AS P
    ON P.ID = I.IDPREDMETA
WHERE SP.NAZIV LIKE '%Matematika%' AND (0 < POSITION(D.IME, ' ') OR 0 < POSITION(D.PREZIME, ' '))
    AND LOWER(SS.NAZIV) LIKE '%budzet%';

--2. zadatak

WITH TRECA AS(
    SELECT D.INDEKS, SP.ID,SP.NAZIV, D.IME, D.PREZIME, D.MESTORODJENJA
    FROM DA.DOSIJE AS D JOIN DA.STUDIJSKIPROGRAM AS SP ON SP.ID = D.IDPROGRAMA
    WHERE 3 = (SELECT COUNT(*)
               FROM DA.UPISGODINE AS UG
               WHERE UG.INDEKS = D.INDEKS)
    AND SP.IDNIVOA = 1 AND 90 < (SELECT SUM(ESPB)
                                 FROM DA.ISPIT AS I JOIN DA.PREDMET AS P ON P.ID = I.IDPREDMETA
                                 WHERE I.INDEKS = D.INDEKS AND I.STATUS = 'o' AND I.OCENA >5)
), BODOVI AS(
    SELECT I.INDEKS, SUM(P.ESPB) SUMA
    FROM DA.ISPIT AS I JOIN DA.PREDMET AS P ON P.ID = I.IDPREDMETA
    WHERE OCENA > 5 AND STATUS = 'o'
    GROUP BY I.INDEKS
)
SELECT T.IME, T.PREZIME, SUBSTR(T.MESTORODJENJA, 1,1)||UPPER(T.MESTORODJENJA, LENGTH(T.MESTORODJENJA))
FROM TRECA AS T JOIN BODOVI AS B ON B.INDEKS = T.INDEKS
WHERE B.SUMA >= 90 AND NOT EXISTS(SELECT *
                                  FROM TRECA AS T1
                                  WHERE T1.INDEKS <> T.INDEKS AND T1.ID = T.ID AND T1.MESTORODJENJA = T.MESTORODJENJA);


CREATE TABLE STUDENTSKA_ORGANIZACIJA(
    ID INTEGER NOT NULL PRIMARY KEY,
    IME VARCHAR(50),
    PREZIME VARCHAR(50),
    TIM VARCHAR(2),
    DATUM_UCLANJENJA_U_ORG DATE DEFAULT CURRENT DATE,
    DATUM_UCLANJENJA_U_TIIM DATE,
    UPRAVNI_ODBOR BOOLEAN DEFAULT FALSE,
    FOREIGN KEY FK_ID (ID) REFERENCES DA.DOSIJE
);

CREATE FUNCTION CLAN_ORGANIZACIJE(I INTEGER)
RETURNS VARCHAR(40)
RETURN CASE WHEN I IN (SELECT ID
             FROM STUDENTSKA_ORGANIZACIJA) THEN 'Student jeste clan'
        ELSE 'Student nije clan' end;

INSERT INTO STUDENTSKA_ORGANIZACIJA(ID, IME, PREZIME, TIM, DATUM_UCLANJENJA_U_ORG, DATUM_UCLANJENJA_U_TIIM)
SELECT D.INDEKS, D.IME, D.PREZIME, CASE WHEN SP.NAZIV LIKE '%Informatika%' THEN 'IT'
                                      WHEN SP.NAZIV LIKE '%Astronomija%' THEN 'CR'
                                      WHEN SP.NAZIV LIKE '%Matematika%' THEN 'HR' ELSE 'PR' END, D.DATUPISA, DATE('15.03.2025')
FROM DA.DOSIJE AS D JOIN DA.STUDIJSKIPROGRAM AS SP ON SP.ID = D.IDPROGRAMA
WHERE D.MESTORODJENJA LIKE 'Novi Sad%';

UPDATE STUDENTSKA_ORGANIZACIJA AS SO1
SET UPRAVNI_ODBOR = TRUE
WHERE SO1.DATUM_UCLANJENJA_U_ORG = (SELECT MIN(SO2.DATUM_UCLANJENJA_U_ORG)
                                    FROM STUDENTSKA_ORGANIZACIJA AS SO2);

CREATE TRIGGER PREKVALIFIKACIJA
    BEFORE UPDATE ON STUDENTSKA_ORGANIZACIJA
        REFERENCING OLD AS O NEW AS N
    FOR EACH ROW
    WHEN(O.TIM <> N.TIM AND (DATE(O.DATUM_UCLANJENJA_U_ORG))
        + 6 MONTHS > CURRENT_DATE)
        BEGIN ATOMIC
            SIGNAL SQLSTATE '75000' ('Nije proslo dovoljno vremena');
        end;


MERGE INTO STUDENTSKA_ORGANIZACIJA AS SO
USING (SELECT* FROM DA.DOSIJE WHERE DATDIPLOMIRANJA IS NOT NULL) AS TMP
ON TMP.INDEKS = SO.ID
WHEN MATCHED THEN DELETE;

DROP TRIGGER PREKVALIFIKACIJA;
DROP TABLE STUDENTSKA_ORGANIZACIJA;
DROP FUNCTION CLAN_ORGANIZACIJE;