SELECT CASE WHEN POL = 'z' THEN 'Studentkinja '
    ELSE 'Student ' END || D.IME || ' ' || D.PREZIME AS
    "Student/kinja", D.INDEKS, SP.NAZIV,
    CASE WHEN POSITION(' ', SP.NAZIV) > 0 THEN SUBSTR(SP.NAZIV, 1,
    POSITION(' ', SP.NAZIV)) ELSE SP.NAZIV END AS "Nivo studija"
FROM DA.DOSIJE AS D JOIN DA.STUDIJSKIPROGRAM AS SP
    ON SP.ID = D.IDPROGRAMA
WHERE D.DATUPISA = (SELECT MAX(D1.DATUPISA)
                 FROM DA.DOSIJE AS D1
                 WHERE D1.IDPROGRAMA = D.IDPROGRAMA);

SELECT DISTINCT D1.IME || ' ' || D1.PREZIME, 'Polozeno ' || COUNT(I1.IDPREDMETA) || ' predmeta od 6 espb' AS PORUKA
FROM DA.DOSIJE AS D1 JOIN DA.ISPIT AS I1 ON I1.INDEKS = D1.INDEKS
AND I1.OCENA > 5 AND I1.STATUS = 'o' JOIN DA.PREDMET AS P1 ON P1.ID = I1.IDPREDMETA
WHERE P1.ESPB = 6 AND NOT EXISTS(SELECT*
                                 FROM DA.ISPIT AS I JOIN DA.PREDMET AS P ON P.ID = I.IDPREDMETA
                                 WHERE I.STATUS = 'o' AND I.OCENA >5
                                 AND I.INDEKS = D1.INDEKS AND P.ESPB > 20)
GROUP BY D1.INDEKS, D1.IME, D1.PREZIME
HAVING COUNT(I1.IDPREDMETA) > 10
UNION
SELECT DISTINCT D2.IME || ' ' || D2.PREZIME, 'Polozen najtezi predmet' AS PORUKA
FROM DA.DOSIJE AS D2 JOIN DA.ISPIT AS I2 ON I2.INDEKS = D2.INDEKS
AND I2.STATUS = 'o' AND I2.OCENA > 5 JOIN DA.PREDMET AS P2 ON P2.ID = I2.IDPREDMETA
WHERE P2.ESPB = (SELECT MAX(P.ESPB)
                 FROM DA.PREDMET AS P);

DROP TABLE IF EXISTS stats;

CREATE TABLE stats(
    INDEKS INTEGER NOT NULL PRIMARY KEY,
    SEST INTEGER DEFAULT 0,
    SEDAM INTEGER DEFAULT 0,
    OSAM INTEGER DEFAULT 0,
    DEVET INTEGER DEFAULT 0,
    DESET INTEGER DEFAULT 0,
    POLOZENO_PREDMETA INTEGER
);

CREATE FUNCTION IZRACUNAJ_PROSEK(SS INTEGER, S INTEGER, O INTEGER, DV INTEGER, DS INTEGER)
RETURNS DOUBLE
RETURN VALUES((SS*6.0+S*7.0+O*8.0+DV*9.0+DS*10.0)/(SS+S+O+DV+DS+0.0));

INSERT INTO stats(INDEKS, SEDAM, OSAM)
SELECT D.INDEKS, SUM(CASE WHEN I.OCENA = 7 THEN 1 ELSE 0 END),
       SUM(CASE WHEN I.OCENA = 8 THEN 1 ELSE 0 END)
FROM DA.DOSIJE AS D JOIN DA.ISPIT AS I ON I.INDEKS = D.INDEKS
AND I.OCENA > 5 AND I.STATUS = 'o'
WHERE NOT EXISTS(SELECT*
                 FROM DA.ISPIT AS I1
                 WHERE I1.INDEKS = I.INDEKS
                 AND I1.STATUS = 'o' AND I1.OCENA = 6)
GROUP BY D.INDEKS;

CREATE TRIGGER okidacStats
    BEFORE INSERT ON stats
    REFERENCING NEW AS N
    FOR EACH ROW
    BEGIN ATOMIC
        SET (N.SEST, N.SEDAM, N.OSAM, N.DEVET, N.DESET, N.POLOZENO_PREDMETA) =
            (SELECT SUM(CASE WHEN I.OCENA = 6 THEN 1 ELSE 0 END), SUM(CASE WHEN I.OCENA = 7 THEN 1 ELSE 0 END),
                    SUM(CASE WHEN I.OCENA = 8 THEN 1 ELSE 0 END),SUM(CASE WHEN I.OCENA = 9 THEN 1 ELSE 0 END),
                    SUM(CASE WHEN I.OCENA = 10 THEN 1 ELSE 0 END), COUNT(*)
             FROM DA.ISPIT AS I
             WHERE I.OCENA > 5 AND I.STATUS = 'o' AND I.INDEKS = N.INDEKS);
    end;

DROP TABLE stats;
DROP TRIGGER  okidacStats;
DROP FUNCTION IZRACUNAJ_PROSEK;