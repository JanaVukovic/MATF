SELECT P1.NAZIV, P2.NAZIV
FROM DA.PREDMET AS P1 JOIN DA.PREDMET AS P2
ON P1.ID < P2.ID AND P1.ESPB = P2.ESPB
WHERE LENGTH(P2.NAZIV) > 4 AND SUBSTR(P1.NAZIV, 4, 2) = 'ri'
AND EXISTS(SELECT *
           FROM DA.ISPIT AS I1 JOIN DA.ISPIT AS I2
           ON I1.INDEKS = I2.INDEKS AND I1.SKGODINA = I2.SKGODINA
           AND I1.STATUS = 'o' AND I1.OCENA > 5 AND I2.STATUS = 'o'
           AND I2.OCENA > 5 AND I1.IDPREDMETA < I2.IDPREDMETA
           WHERE I1.IDPREDMETA = P1.ID AND I2.IDPREDMETA = P2.ID);

CREATE TABLE SMEROVI(
    ID INTEGER NOT NULL PRIMARY KEY,
    NAZIV VARCHAR(100),
    NIVO VARCHAR(100),
    STUDENTI INTEGER,
    PROSEK DECIMAL,
    CONSTRAINT nivo_OGR CHECK(NIVO IN ('osnovne', 'master','doktorske'))
);

CREATE FUNCTION TO_CM(DUZINA INTEGER, MERA CHAR(1))
RETURNS INTEGER
RETURN (CASE WHEN LOWER(MERA) = 'd' THEN DUZINA*10
    WHEN LOWER(MERA) = 'm' THEN DUZINA*100
    WHEN LOWER(MERA) = 'k' THEN DUZINA*1000
    ELSE -1 END);

INSERT INTO SMEROVI(ID, NAZIV, NIVO, STUDENTI)
SELECT SP.ID, SP.NAZIV, 'osnovne',COUNT(DISTINCT INDEKS)
FROM DA.STUDIJSKIPROGRAM AS SP JOIN DA.DOSIJE AS D ON D.IDPROGRAMA = SP.ID
WHERE SP.IDNIVOA = 1
GROUP BY SP.ID, SP.NAZIV;

MERGE INTO SMEROVI AS S
    USING(SELECT SP.ID, SP.NAZIV, CASE WHEN SP.IDNIVOA = 1 THEN 'osnovne'
          WHEN SP.IDNIVOA = 2 THEN 'master' ELSE 'doktorske' END as NIVO,
              COUNT(DISTINCT D.INDEKS) AS BROJ, AVG(OCENA) AS PROSEK
          FROM DA.DOSIJE AS D JOIN DA.STUDIJSKIPROGRAM AS SP
          ON SP.ID = D.IDPROGRAMA LEFT JOIN DA.ISPIT AS I
          ON I.INDEKS = D.INDEKS AND I.OCENA > 5 AND I.STATUS = 'o'
          GROUP BY SP.ID, SP.NAZIV, SP.IDNIVOA) AS TMP
ON (TMP.ID = S.ID)
WHEN MATCHED THEN
    UPDATE
    SET S.PROSEK = TMP.PROSEK
WHEN NOT MATCHED THEN
    INSERT VALUES(TMP.ID, TMP.NAZIV, TMP.NIVO, TMP.BROJ, TMP.PROSEK);

DELETE FROM SMEROVI
WHERE STUDENTI < 100 AND PROSEK > 9.0;
