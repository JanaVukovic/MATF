SELECT IME, PREZIME, COALESCE(MONTHNAME(DATDIPLOMIRANJA), 'NIJE'), P.NAZIV
FROM DA.DOSIJE AS D JOIN DA.UPISANKURS AS UK
ON UK.INDEKS = D.INDEKS JOIN DA.PREDMET AS P
ON P.ID = UK.IDPREDMETA
WHERE 3 <= (SELECT COUNT(*)
             FROM DA.ISPIT AS I
             WHERE I.INDEKS = D.INDEKS
             AND I.OCENA >= 9 AND I.STATUS = 'o'
             AND DATE(I.DATPOLAGANJA) + 6 YEAR >= CURRENT_DATE)
AND NOT EXISTS(SELECT*
               FROM DA.ISPIT AS I
               WHERE I.INDEKS = D.INDEKS
               AND I.IDPREDMETA = UK.IDPREDMETA
               AND I.STATUS = 'o' AND I.OCENA >5)
ORDER BY P.NAZIV DESC;

CREATE TABLE APSOLVENT(
    INDEKS INTEGER PRIMARY KEY,
    POENADOKRAJA INTEGER,
    GODINASTUDIJA INTEGER,
    VREMEUNOSA DATE DEFAULT CURRENT_DATE
);

CREATE FUNCTION IS_POLOZENO(STUDENT INTEGER, PREDMET INTEGER)
RETURNS BOOLEAN
RETURN STUDENT IN (SELECT INDEKS
                   FROM DA.ISPIT
                   WHERE STATUS = 'o' AND IDPREDMETA = PREDMET
                   AND OCENA > 5);

INSERT INTO APSOLVENT(INDEKS, POENADOKRAJA, GODINASTUDIJA)
SELECT D.INDEKS, SP.OBIMESPB - SUM(P.ESPB), YEAR(CURRENT_DATE - DATE(DATUPISA))
FROM DA.DOSIJE AS D JOIN DA.ISPIT AS I ON I.INDEKS = D.INDEKS
AND I.OCENA > 5 AND I.STATUS = 'o' JOIN DA.STUDIJSKIPROGRAM AS SP
ON SP.ID = D.IDPROGRAMA JOIN DA.PREDMET AS P ON P.ID = I.IDPREDMETA
GROUP BY D.INDEKS, SP.OBIMESPB, DATUPISA
HAVING SP.OBIMESPB-SUM(P.ESPB) < 30;

CREATE TRIGGER UNOS_ISPITA
    AFTER INSERT ON DA.ISPIT
    REFERENCING NEW AS N
    FOR EACH ROW
    WHEN(N.STATUS = 'o' AND N.OCENA > 5)
    BEGIN ATOMIC
        UPDATE APSOLVENT AS A
        SET A.POENADOKRAJA = A.POENADOKRAJA - (SELECT ESPB
                                               FROM DA.PREDMET AS P
                                               WHERE P.ID = N.IDPREDMETA)
        WHERE A.INDEKS = N.INDEKS;
    end;

DELETE FROM APSOLVENT
WHERE POENADOKRAJA = 0;
